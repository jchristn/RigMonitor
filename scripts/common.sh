#!/usr/bin/env bash
# Shared helpers for the RigMonitor Linux, macOS, WSL, and WSL2 scripts.
# Sourced by scripts/<os>/*.sh; not meant to be run directly.
#
# Environment overrides:
#   RIGMONITOR_CONFIGURATION  dotnet build configuration (default: Release)
#   RIGMONITOR_SETTINGS       settings file (default: <repo>/rigmonitor.json)

RM_SCRIPTS_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
RM_ROOT="$(cd -- "$RM_SCRIPTS_DIR/.." && pwd)"
RM_CONFIGURATION="${RIGMONITOR_CONFIGURATION:-Release}"
RM_SERVER_PROJECT="$RM_ROOT/src/RigMonitor.Server/RigMonitor.Server.csproj"
RM_RUN_DIR="$RM_ROOT/.rigmonitor-native"
RM_SERVER_DLL="$RM_RUN_DIR/RigMonitor.Server.dll"
RM_SERVER_EXE="$RM_RUN_DIR/RigMonitor.Server"
RM_SETTINGS_FILE="${RIGMONITOR_SETTINGS:-$RM_ROOT/rigmonitor.json}"
RM_PID_FILE="$RM_RUN_DIR/rigmonitor.pid"
RM_ENV_FILE="$RM_RUN_DIR/startup.env"
RM_LOG_DIR="$RM_ROOT/data/logs"
RM_CONSOLE_LOG="$RM_LOG_DIR/console.log"

rm_log() { echo "[rigmonitor] $*"; }
rm_die() { echo "[rigmonitor] ERROR: $*" >&2; exit 1; }

rm_start_usage() {
  cat <<EOF
Usage: $(basename "$0") [--foreground]

Builds the dashboard and server, then starts RigMonitor in the background.
If it is already running, it is restarted on the new build.

  --foreground   Run in the foreground without rebuilding (builds only if no
                 build exists). Used by systemd/launchd/startup launchers.
EOF
}

# Parses start arguments into RM_FOREGROUND.
rm_parse_start_args() {
  RM_FOREGROUND=0
  while [ $# -gt 0 ]; do
    case "$1" in
      --foreground) RM_FOREGROUND=1 ;;
      -h|--help) rm_start_usage; exit 0 ;;
      *) rm_start_usage >&2; exit 2 ;;
    esac
    shift
  done
}

# Loads the PATH/DOTNET_ROOT captured by install-at-startup, so supervisors
# (systemd, launchd, Windows logon) can find dotnet and npm.
rm_load_env() {
  if [ -f "$RM_ENV_FILE" ]; then
    # shellcheck disable=SC1090
    . "$RM_ENV_FILE"
  fi
}

rm_write_env_file() {
  mkdir -p "$RM_RUN_DIR"
  {
    echo "# Generated by scripts/*/install-at-startup.sh on $(date)"
    printf 'export PATH=%q\n' "$PATH"
    if [ -n "${DOTNET_ROOT:-}" ]; then
      printf 'export DOTNET_ROOT=%q\n' "$DOTNET_ROOT"
    fi
    if [ -n "${RIGMONITOR_CONFIGURATION:-}" ]; then
      printf 'export RIGMONITOR_CONFIGURATION=%q\n' "$RIGMONITOR_CONFIGURATION"
    fi
    if [ -n "${RIGMONITOR_SETTINGS:-}" ]; then
      printf 'export RIGMONITOR_SETTINGS=%q\n' "$RIGMONITOR_SETTINGS"
    fi
  } > "$RM_ENV_FILE"
}

rm_is_built() {
  [ -f "$RM_SERVER_DLL" ]
}

rm_build() {
  command -v npm >/dev/null 2>&1 || rm_die "npm not found on PATH"
  command -v dotnet >/dev/null 2>&1 || rm_die "dotnet not found on PATH"

  rm_log "Building dashboard"
  (
    cd "$RM_ROOT/dashboard"
    if [ -f package-lock.json ]; then npm ci; else npm install; fi
    npm run build
  ) || rm_die "dashboard build failed"

  rm_log "Building server ($RM_CONFIGURATION)"
  mkdir -p "$RM_RUN_DIR"
  dotnet build "$RM_SERVER_PROJECT" -c "$RM_CONFIGURATION" -o "$RM_RUN_DIR" || rm_die "server build failed"
}

# Builds only when no build exists (supervised/boot-time path).
rm_ensure_built() {
  if ! rm_is_built; then
    rm_build
  fi
}

# Prints the PID of the running instance, or nothing.
rm_running_pid() {
  local pid=""
  if [ -f "$RM_PID_FILE" ]; then
    pid="$(tr -cd '0-9' < "$RM_PID_FILE")"
    if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
      echo "$pid"
      return 0
    fi
  fi
  # Fall back to matching the runtime path, for instances started elsewhere.
  if command -v pgrep >/dev/null 2>&1; then
    pid="$(pgrep -f "$RM_RUN_DIR/RigMonitor.Server" 2>/dev/null | head -n 1 || true)"
    if [ -n "$pid" ]; then
      echo "$pid"
      return 0
    fi
  fi
  return 1
}

rm_port() {
  local port=""
  if [ -f "$RM_SETTINGS_FILE" ]; then
    port="$(grep -io '"port"[[:space:]]*:[[:space:]]*[0-9]*' "$RM_SETTINGS_FILE" | head -n 1 | grep -o '[0-9]*$' || true)"
  fi
  echo "${port:-9990}"
}

rm_print_urls() {
  local port
  port="$(rm_port)"
  rm_log "Dashboard: http://localhost:$port/dashboard"
  rm_log "OpenAPI:   http://localhost:$port/openapi"
}

# Runs the server in the foreground, replacing the current shell so the
# supervisor's PID is the server's PID.
rm_exec_foreground() {
  mkdir -p "$RM_LOG_DIR"
  cd "$RM_ROOT"
  echo "$$" > "$RM_PID_FILE"
  if [ -x "$RM_SERVER_EXE" ]; then
    exec "$RM_SERVER_EXE" --settings "$RM_SETTINGS_FILE"
  fi
  exec dotnet "$RM_SERVER_DLL" --settings "$RM_SETTINGS_FILE"
}

rm_launch_background() {
  mkdir -p "$RM_LOG_DIR"
  cd "$RM_ROOT"
  local cmd
  if [ -x "$RM_SERVER_EXE" ]; then
    cmd=("$RM_SERVER_EXE" --settings "$RM_SETTINGS_FILE")
  else
    cmd=(dotnet "$RM_SERVER_DLL" --settings "$RM_SETTINGS_FILE")
  fi
  if command -v setsid >/dev/null 2>&1; then
    setsid "${cmd[@]}" >> "$RM_CONSOLE_LOG" 2>&1 < /dev/null &
  else
    nohup "${cmd[@]}" >> "$RM_CONSOLE_LOG" 2>&1 < /dev/null &
  fi
  local pid=$!
  echo "$pid" > "$RM_PID_FILE"
  sleep 2
  if ! kill -0 "$pid" 2>/dev/null; then
    rm -f "$RM_PID_FILE"
    rm_die "RigMonitor exited during startup; see $RM_CONSOLE_LOG"
  fi
  rm_log "Started RigMonitor (PID $pid)"
  rm_log "Console log: $RM_CONSOLE_LOG"
  rm_print_urls
}

# Foreground flow for supervisors: build only if missing, then exec.
rm_start_foreground() {
  rm_load_env
  rm_ensure_built
  local pid
  if pid="$(rm_running_pid)"; then
    rm_log "RigMonitor is already running (PID $pid)"
    exit 0
  fi
  rm_exec_foreground
}

# Unsupervised start: always build, then start, restarting any running
# instance so it picks up the new build. The build runs first, so a failed
# build leaves the running instance untouched.
rm_start_direct() {
  rm_load_env
  rm_build
  if rm_running_pid >/dev/null; then
    rm_log "Restarting on the new build"
    rm_stop_direct
  fi
  rm_launch_background
}

# Stops an unsupervised instance: SIGTERM, wait, then SIGKILL.
rm_stop_direct() {
  local pid
  if ! pid="$(rm_running_pid)"; then
    rm_log "RigMonitor is not running"
    rm -f "$RM_PID_FILE"
    return 0
  fi
  rm_log "Stopping RigMonitor (PID $pid)"
  kill -TERM "$pid" 2>/dev/null || true
  local i=0
  while kill -0 "$pid" 2>/dev/null && [ $i -lt 30 ]; do
    sleep 1
    i=$((i + 1))
  done
  if kill -0 "$pid" 2>/dev/null; then
    rm_log "Process did not exit after 30s; sending SIGKILL"
    kill -KILL "$pid" 2>/dev/null || true
  fi
  rm -f "$RM_PID_FILE"
  rm_log "Stopped"
}

# ---- systemd helpers (Linux, WSL2 with systemd) ----

RM_SYSTEMD_UNIT="rigmonitor.service"
RM_SYSTEMD_UNIT_FILE="/etc/systemd/system/$RM_SYSTEMD_UNIT"

rm_sudo() {
  if [ "$(id -u)" = "0" ]; then "$@"; else sudo "$@"; fi
}

rm_systemd_available() {
  [ "$(ps -p 1 -o comm= 2>/dev/null | tr -d ' ')" = "systemd" ] && command -v systemctl >/dev/null 2>&1
}

rm_systemd_installed() {
  [ -f "$RM_SYSTEMD_UNIT_FILE" ]
}

# $1 = start script path that systemd should run with --foreground
rm_systemd_install() {
  local start_script="$1"
  local user group tmp
  user="$(id -un)"
  group="$(id -gn)"
  tmp="$(mktemp)"
  cat > "$tmp" <<EOF
[Unit]
Description=RigMonitor telemetry daemon
Documentation=https://github.com/jchristn/RigMonitor
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=$user
Group=$group
WorkingDirectory=$RM_ROOT
ExecStart=/bin/bash "$start_script" --foreground
Restart=on-failure
RestartSec=5
TimeoutStopSec=30

[Install]
WantedBy=multi-user.target
EOF
  rm_log "Installing $RM_SYSTEMD_UNIT_FILE (requires sudo)"
  rm_sudo install -m 0644 "$tmp" "$RM_SYSTEMD_UNIT_FILE"
  rm -f "$tmp"
  rm_sudo systemctl daemon-reload
  rm_sudo systemctl enable "$RM_SYSTEMD_UNIT"
}

rm_systemd_remove() {
  if ! rm_systemd_installed; then
    rm_log "$RM_SYSTEMD_UNIT is not installed"
    return 0
  fi
  rm_log "Disabling and stopping $RM_SYSTEMD_UNIT (requires sudo)"
  rm_sudo systemctl disable --now "$RM_SYSTEMD_UNIT" || true
  rm_sudo rm -f "$RM_SYSTEMD_UNIT_FILE"
  rm_sudo systemctl daemon-reload
  rm -f "$RM_PID_FILE"
  rm_log "Removed $RM_SYSTEMD_UNIT"
}

# ---- Windows-side helpers (WSL, WSL2) ----

rm_require_wsl() {
  [ -n "${WSL_DISTRO_NAME:-}" ] || grep -qi microsoft /proc/version 2>/dev/null || rm_die "this script must be run inside WSL"
  command -v powershell.exe >/dev/null 2>&1 || rm_die "powershell.exe not found; enable Windows interop (appendWindowsPath) in /etc/wsl.conf"
  command -v iconv >/dev/null 2>&1 || rm_die "iconv not found"
  command -v base64 >/dev/null 2>&1 || rm_die "base64 not found"
  [ -n "${WSL_DISTRO_NAME:-}" ] || rm_die "WSL_DISTRO_NAME is not set"
}

# Quotes a value as a PowerShell single-quoted string literal.
rm_ps_quote() {
  printf "'%s'" "$(printf '%s' "$1" | sed "s/'/''/g")"
}

# Runs a PowerShell script (passed on stdin) on the Windows host.
rm_run_powershell() {
  local encoded
  encoded="$(iconv -f UTF-8 -t UTF-16LE | base64 | tr -d '\n')"
  # Run from a Windows directory to avoid UNC working-directory warnings.
  (cd /mnt/c 2>/dev/null || true; powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand "$encoded") | tr -d '\r'
  return "${PIPESTATUS[0]}"
}

# Installs a Windows Startup-folder shortcut that launches this distro at logon.
# $1 = mode: "start" (run start script in foreground) or "keepalive" (keep a
#      systemd-enabled distro running so its enabled services stay up)
# $2 = start script path inside the distro (used in "start" mode)
# $3 = "1" to also launch it immediately
rm_windows_startup_install() {
  local mode="$1" start_script="$2" start_now='$false'
  [ "${3:-0}" = "1" ] && start_now='$true'
  rm_run_powershell <<EOF
\$ErrorActionPreference = 'Stop'
\$distro = $(rm_ps_quote "$WSL_DISTRO_NAME")
\$user = $(rm_ps_quote "$(id -un)")
\$script = $(rm_ps_quote "$start_script")
\$mode = $(rm_ps_quote "$mode")
\$dir = Join-Path \$env:LOCALAPPDATA 'RigMonitor'
New-Item -ItemType Directory -Force -Path \$dir | Out-Null
\$launcher = Join-Path \$dir 'rigmonitor-wsl-launcher.ps1'
\$launcherBody = @'
param([string]\$Distro, [string]\$User, [string]\$Script, [string]\$Mode)
if (\$Mode -eq 'keepalive') {
    & wsl.exe -d \$Distro -u \$User --exec /bin/sleep infinity
} else {
    & wsl.exe -d \$Distro -u \$User --exec /bin/bash \$Script --foreground
}
'@
Set-Content -Path \$launcher -Value \$launcherBody -Encoding UTF8
\$lnk = Join-Path ([Environment]::GetFolderPath('Startup')) ('RigMonitor (WSL ' + \$distro + ').lnk')
\$shell = New-Object -ComObject WScript.Shell
\$s = \$shell.CreateShortcut(\$lnk)
\$s.TargetPath = Join-Path \$env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
\$s.Arguments = '-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File "' + \$launcher + '" -Distro "' + \$distro + '" -User "' + \$user + '" -Script "' + \$script + '" -Mode "' + \$mode + '"'
\$s.WorkingDirectory = \$env:USERPROFILE
\$s.WindowStyle = 7
\$s.Description = 'Start RigMonitor in WSL distro ' + \$distro
\$s.Save()
Write-Output ('[rigmonitor] Installed Windows startup shortcut: ' + \$lnk)
if ($start_now) {
    Start-Process -FilePath \$lnk
    Write-Output '[rigmonitor] Launched startup shortcut'
}
EOF
}

rm_windows_startup_installed() {
  local out
  out="$(rm_run_powershell <<EOF
\$lnk = Join-Path ([Environment]::GetFolderPath('Startup')) ('RigMonitor (WSL ' + $(rm_ps_quote "$WSL_DISTRO_NAME") + ').lnk')
if (Test-Path -LiteralPath \$lnk) { 'yes' } else { 'no' }
EOF
)" || return 1
  [ "$out" = "yes" ]
}

# Launches the installed Windows startup shortcut for this distro now.
rm_windows_startup_launch() {
  rm_run_powershell <<EOF
\$ErrorActionPreference = 'Stop'
\$lnk = Join-Path ([Environment]::GetFolderPath('Startup')) ('RigMonitor (WSL ' + $(rm_ps_quote "$WSL_DISTRO_NAME") + ').lnk')
Start-Process -FilePath \$lnk
Write-Output '[rigmonitor] Launched Windows startup shortcut'
EOF
}

rm_windows_startup_remove() {
  rm_run_powershell <<EOF
\$ErrorActionPreference = 'Stop'
\$distro = $(rm_ps_quote "$WSL_DISTRO_NAME")
\$startup = [Environment]::GetFolderPath('Startup')
\$lnk = Join-Path \$startup ('RigMonitor (WSL ' + \$distro + ').lnk')
if (Test-Path -LiteralPath \$lnk) {
    Remove-Item -LiteralPath \$lnk -Force
    Write-Output ('[rigmonitor] Removed Windows startup shortcut: ' + \$lnk)
} else {
    Write-Output '[rigmonitor] No Windows startup shortcut found for this distro'
}
\$remaining = @(Get-ChildItem -LiteralPath \$startup -Filter 'RigMonitor (WSL *).lnk' -ErrorAction SilentlyContinue)
\$launcher = Join-Path (Join-Path \$env:LOCALAPPDATA 'RigMonitor') 'rigmonitor-wsl-launcher.ps1'
if (\$remaining.Count -eq 0 -and (Test-Path -LiteralPath \$launcher)) {
    Remove-Item -LiteralPath \$launcher -Force
}
EOF
}
